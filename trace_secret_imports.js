/**
 * trace_secret_imports.js
 *
 * Full dependency-graph analysis tracing imports from Client Components
 * to server-only modules (Prisma initialization, environment validation, auth secrets).
 *
 * Checks:
 * - Direct or transitive imports of `src/lib/security/env-validation.ts`
 * - Direct or transitive imports of `src/lib/db/prisma.ts` (Prisma instance initialization)
 * - Direct or transitive imports of `src/lib/auth/session.ts` or `src/lib/auth/tokens.ts` (private auth secrets/cookies)
 * - Direct or transitive imports of `server-only` or `next/headers`
 *
 * Boundaries:
 * - 'use client' declares a Client Component root.
 * - 'use server' declares a Server Action boundary (RPC stub generated by Next.js, not bundled).
 * - Type imports (`import type`, `export type`) are erased at compile time.
 * - Path aliases (`@/*`) and relative imports are fully resolved.
 */

const fs = require('fs');
const path = require('path');

const ROOT_DIR = __dirname;
const SRC_DIR = path.join(ROOT_DIR, 'src');

const SERVER_TARGET_PATTERNS = [
  { name: 'Environment Validation (DATABASE_URL / AUTH_SECRET)', pattern: /lib[/\\]security[/\\]env-validation/ },
  { name: 'Prisma Client Instance (DB Initialization)', pattern: /lib[/\\]db[/\\]prisma/ },
  { name: 'Private Auth Session & Tokens', pattern: /lib[/\\]auth[/\\](session|tokens)\.ts/ },
  { name: 'Server-Only Guard Package', pattern: /\[package:server-only\]/ },
  { name: 'Server Headers / Cookies Package', pattern: /\[package:next\/headers\]/ },
];

const SERVER_PACKAGES = ['server-only', 'next/headers', 'crypto', 'bcryptjs'];

function normalize(p) {
  return path.resolve(p).replace(/\\/g, '/');
}

function getAllFiles(dir, extensions = ['.ts', '.tsx', '.js', '.jsx']) {
  let results = [];
  if (!fs.existsSync(dir)) return results;
  for (const item of fs.readdirSync(dir)) {
    const full = path.join(dir, item);
    const stat = fs.statSync(full);
    if (stat.isDirectory()) {
      if (item !== 'node_modules' && item !== '.next') {
        results = results.concat(getAllFiles(full, extensions));
      }
    } else if (extensions.includes(path.extname(full))) {
      results.push(full);
    }
  }
  return results;
}

function hasDirective(filePath, directive) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    const snippet = content.slice(0, 1000);
    const regex = new RegExp(`^\\s*['"]${directive}['"]`, 'm');
    return regex.test(snippet);
  } catch {
    return false;
  }
}

function resolveImport(specifier, currentFile) {
  if (SERVER_PACKAGES.includes(specifier)) {
    return `[package:${specifier}]`;
  }
  if (!specifier.startsWith('.') && !specifier.startsWith('@/')) {
    return null;
  }

  let basePath;
  if (specifier.startsWith('@/')) {
    basePath = path.join(SRC_DIR, specifier.slice(2));
  } else {
    basePath = path.resolve(path.dirname(currentFile), specifier);
  }

  const extensions = ['', '.ts', '.tsx', '.js', '.jsx', '/index.ts', '/index.tsx', '/index.js', '/index.jsx'];
  for (const ext of extensions) {
    const candidate = basePath + ext;
    if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) {
      return candidate;
    }
  }

  return null;
}

function extractImports(filePath) {
  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');
  const imports = [];

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i].trim();
    if (line.startsWith('//') || line.startsWith('/*') || line.startsWith('*')) continue;
    if (!line.includes('import') && !line.includes('export')) continue;

    const isTypeOnly = /^\s*import\s+type\s+/.test(line) || /^\s*export\s+type\s+/.test(line);

    const fromMatch = line.match(/\bfrom\s+['"]([^'"]+)['"]/);
    const directMatch = line.match(/^\s*import\s+['"]([^'"]+)['"]/);

    const specifier = fromMatch ? fromMatch[1] : (directMatch ? directMatch[1] : null);
    if (specifier) {
      imports.push({
        specifier,
        line: i + 1,
        raw: line,
        isTypeOnly,
      });
    }
  }

  return imports;
}

function matchServerTarget(targetPath) {
  if (!targetPath) return null;
  const normalized = targetPath.startsWith('[') ? targetPath : normalize(targetPath);
  for (const target of SERVER_TARGET_PATTERNS) {
    if (target.pattern.test(normalized)) {
      return target.name;
    }
  }
  return null;
}

function trace() {
  console.log('='.repeat(80));
  console.log('TRACE SECRET IMPORTS - Next.js Client-to-Server Import Graph Tracer');
  console.log('='.repeat(80));

  const allFiles = getAllFiles(SRC_DIR);
  const clientFiles = allFiles.filter(f => hasDirective(f, 'use client'));

  console.log(`Discovered ${allFiles.length} source files in src/`);
  console.log(`Discovered ${clientFiles.length} Client Components ('use client')\n`);

  const fileMap = new Map();
  for (const file of allFiles) {
    fileMap.set(file, extractImports(file));
  }

  const leaks = [];

  for (const clientFile of clientFiles) {
    const visited = new Set();

    function search(currentPath) {
      const current = currentPath[currentPath.length - 1];
      const currentFile = current.file;

      const serverTargetName = matchServerTarget(currentFile);
      if (serverTargetName) {
        leaks.push({
          clientComponent: path.relative(ROOT_DIR, clientFile),
          targetName: serverTargetName,
          targetFile: currentFile,
          path: [...currentPath],
        });
        return;
      }

      if (visited.has(currentFile)) return;
      visited.add(currentFile);

      // Next.js 'use server' boundary: Server Actions do not bundle into the client
      if (currentPath.length > 1 && hasDirective(currentFile, 'use server')) {
        return;
      }

      const imps = fileMap.get(currentFile) || [];
      for (const imp of imps) {
        if (imp.isTypeOnly) continue; // Erasure of type imports

        const resolved = resolveImport(imp.specifier, currentFile);
        if (resolved) {
          search([...currentPath, { file: resolved, import: imp }]);
        }
      }
    }

    search([{ file: clientFile, import: null }]);
  }

  if (leaks.length === 0) {
    console.log('[PASS] ZERO server-only modules reach any Client Component:');
    console.log('  - Environment validation (DATABASE_URL / AUTH_SECRET): ISOLATED (Server-Only)');
    console.log('  - Prisma Client initialization (prisma.ts):           ISOLATED (Server-Only)');
    console.log('  - Server authentication secrets & session cookies:    ISOLATED (Server-Only)');
    console.log('  - Server-only guards and next/headers:                ISOLATED (Server-Only)');
    console.log('='.repeat(80));
    return true;
  } else {
    console.log(`[FAIL] Found ${leaks.length} path(s) leaking server secrets into Client Components:\n`);
    leaks.forEach((leak, idx) => {
      console.log(`[Leak #${idx + 1}] Target: ${leak.targetName}`);
      console.log(`Client Component: ${leak.clientComponent}`);
      console.log('Import Chain:');
      for (let i = 0; i < leak.path.length - 1; i++) {
        const from = path.relative(ROOT_DIR, leak.path[i].file);
        const to = leak.path[i + 1].file.startsWith('[') ? leak.path[i + 1].file : path.relative(ROOT_DIR, leak.path[i + 1].file);
        const imp = leak.path[i + 1].import;
        console.log(`  ${from} (line ${imp.line})`);
        console.log(`    ↳ Code: ${imp.raw}`);
        console.log(`    ↳ Resolves to: ${to}`);
      }
      console.log('');
    });
    console.log('='.repeat(80));
    return false;
  }
}

const ok = trace();
process.exit(ok ? 0 : 1);
